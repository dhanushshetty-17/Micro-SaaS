const authenticateToken = (req, res, next) => {
  const authHeader = req.headers.authorization;

  if (!authHeader) {
    return res.status(401).json({
      success: false,
      message: "Token not provided",
    });
  }

  const token = authHeader.split(" ")[1];

  try {
    const decoded = jwt.verify(token, process.env.JWT_SECRET);
    req.user = decoded;
    next();
  } catch (error) {
    return res.status(403).json({
      success: false,
      message: "Invalid or expired token",
    });
  }
};

const formatDate = (dateValue) => {
  if (!dateValue) return "";
  return new Date(dateValue).toLocaleDateString("en-GB");
};

const createInvoicePdfBuffer = (invoice) => {
  return new Promise((resolve, reject) => {
    const chunks = [];
    const doc = new PDFDocument({ margin: 50, size: "A4" });

    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc.fontSize(24).text("Invoice", { align: "right" });
    doc.moveDown().fontSize(12)
      .text(`Invoice Number: ${invoice.invoice_number}`)
      .text(`Status: ${invoice.status}`)
      .text(`Due Date: ${formatDate(invoice.due_date)}`);

    doc.moveDown(2).fontSize(16).text("Client Details");
    doc.moveDown(0.5).fontSize(12)
      .text(`Name: ${invoice.client_name}`)
      .text(`Email: ${invoice.client_email}`)
      .text(`Phone: ${invoice.client_phone || "-"}`);

    doc.moveDown(2).fontSize(16).text("Invoice Details");
    doc.moveDown(0.5).fontSize(12)
      .text(`Description: ${invoice.description}`)
      .moveDown()
      .fontSize(18)
      .text(`Amount: INR ${invoice.amount}`, { align: "right" });

    doc.moveDown(3).fontSize(10).fillColor("gray").text(
      "Generated by Freelancer Invoice Tracker",
      { align: "center" }
    );

    doc.end();
  });
};

const createInvoicePdf = async (invoice, res) => {
  const pdfBuffer = await createInvoicePdfBuffer(invoice);
  res.setHeader("Content-Type", "application/pdf");
  res.setHeader(
    "Content-Disposition",
    `attachment; filename="${invoice.invoice_number}.pdf"`
  );
  res.send(pdfBuffer);
};

app.post("/login", async (req, res) => {
  const { email, password } = req.body;

  try {
    const result = await pool.query(
      "SELECT * FROM users WHERE email = $1",
      [email]
    );

    if (result.rows.length === 0) {
      return res.json({
        success: false,
        message: "User not found",
      });
    }

    const user = result.rows[0];
    const isMatch = await bcrypt.compare(password, user.password);

    if (!isMatch) {
      return res.json({
        success: false,
        message: "Invalid password",
      });
    }

    const token = jwt.sign(
      { id: user.id, email: user.email },
      process.env.JWT_SECRET,
      { expiresIn: "1h" }
    );

    return res.json({
      success: true,
      message: "Login Successful",
      token,
    });
  } catch (error) {
    console.error(error);
    return res.status(500).json({
      success: false,
      message: "Server Error",
    });
  }
});

