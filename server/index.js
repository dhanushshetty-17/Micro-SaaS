app.post("/invoices/:id/pay", authenticateToken, async (req, res) => {
  try {
    if (!stripe) {
      return res.status(500).json({
        success: false,
        message: "Stripe is not configured",
      });
    }

    const invoiceId = req.params.id;
    const userId = req.user.id;

    const invoiceResult = await pool.query(
      `SELECT *
       FROM invoices
       WHERE id = $1 AND user_id = $2`,
      [invoiceId, userId]
    );

    if (invoiceResult.rows.length === 0) {
      return res.status(404).json({
        success: false,
        message: "Invoice not found",
      });
    }

    const invoice = invoiceResult.rows[0];

    const session = await stripe.checkout.sessions.create({
      payment_method_types: ["card"],
      mode: "payment",
      line_items: [
        {
          price_data: {
            currency: "inr",
            product_data: {
              name: `Invoice ${invoice.invoice_number}`,
            },
            unit_amount: Math.round(Number(invoice.amount) * 100),
          },
          quantity: 1,
        },
      ],
      success_url: `${process.env.CLIENT_URL}/dashboard?payment=success&invoice_id=${invoice.id}`,
      cancel_url: `${process.env.CLIENT_URL}/dashboard?payment=cancelled&invoice_id=${invoice.id}`,
      metadata: {
        invoiceId: String(invoice.id),
        userId: String(userId),
        invoiceNumber: invoice.invoice_number,
      },
    });

    return res.json({
      success: true,
      checkoutUrl: session.url,
    });
  } catch (error) {
    console.error("PAYMENT CREATION ERROR:", error);
    return res.status(500).json({
      success: false,
      message: "Failed to create payment session",
    });
  }
});

app.get("/invoices/:id/pay/verify", authenticateToken, async (req, res) => {
  try {
    if (!stripe) {
      return res.status(500).json({
        success: false,
        message: "Stripe is not configured",
      });
    }

    const invoiceId = req.params.id;
    const userId = req.user.id;
    const { session_id } = req.query;

    if (!session_id) {
      return res.status(400).json({
        success: false,
        message: "Missing Stripe session ID",
      });
    }

    const invoiceResult = await pool.query(
      `SELECT *
       FROM invoices
       WHERE id = $1 AND user_id = $2`,
      [invoiceId, userId]
    );

    if (invoiceResult.rows.length === 0) {
      return res.status(404).json({
        success: false,
        message: "Invoice not found",
      });
    }

    const session = await stripe.checkout.sessions.retrieve(String(session_id));

    if (
      session.payment_status !== "paid" ||
      session.metadata?.invoiceId !== String(invoiceId) ||
      session.metadata?.userId !== String(userId)
    ) {
      return res.status(400).json({
        success: false,
        message: "Payment session does not match this invoice",
      });
    }

    const updatedInvoice = await pool.query(
      `UPDATE invoices
       SET status = 'Paid'
       WHERE id = $1 AND user_id = $2
       RETURNING *`,
      [invoiceId, userId]
    );

    return res.json({
      success: true,
      message: "Payment verified and invoice marked as paid",
      invoice: updatedInvoice.rows[0],
    });
  } catch (error) {
    console.error("PAYMENT VERIFICATION ERROR:", error);
    return res.status(500).json({
      success: false,
      message: "Payment verification failed",
    });
  }
});

app.post("/stripe/webhook", async (req, res) => {
  if (!stripe || !process.env.STRIPE_WEBHOOK_SECRET) {
    return res.status(500).json({
      success: false,
      message: "Stripe webhook is not configured",
    });
  }

  const sig = req.headers["stripe-signature"];

  let event;

  try {
    event = stripe.webhooks.constructEvent(
      req.body,
      sig,
      process.env.STRIPE_WEBHOOK_SECRET
    );
  } catch (error) {
    console.error("WEBHOOK ERROR:", error.message);
    return res.status(400).send(`Webhook Error: ${error.message}`);
  }

  if (event.type === "checkout.session.completed") {
    const session = event.data.object;
    const invoiceId = session.metadata?.invoiceId;

    if (invoiceId && session.payment_status === "paid") {
      await pool.query(
        `UPDATE invoices
         SET status = 'Paid'
         WHERE id = $1 AND status <> 'Paid'`,
        [invoiceId]
      );
    }
  }

  return res.json({ received: true });
});

