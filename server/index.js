app.post("/create-invoice", authenticateToken, async (req, res) => {
  try {
    const { clientName, clientEmail, clientPhone, description, amount, dueDate } = req.body;
    const userId = req.user.id;

    const lastInvoice = await pool.query(
      `SELECT invoice_number
       FROM invoices
       ORDER BY id DESC
       LIMIT 1`
    );

    let invoiceNumber;
    if (lastInvoice.rows.length === 0) {
      invoiceNumber = "INV-1001";
    } else {
      const lastNumber = lastInvoice.rows[0].invoice_number.split("-")[1];
      const nextNumber = Number(lastNumber) + 1;
      invoiceNumber = `INV-${nextNumber}`;
    }

    const result = await pool.query(
      `INSERT INTO invoices
       (
         user_id,
         invoice_number,
         client_name,
         client_email,
         client_phone,
         description,
         amount,
         status,
         due_date
       )
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)
       RETURNING *`,
      [
        userId,
        invoiceNumber,
        clientName,
        clientEmail,
        clientPhone,
        description,
        amount,
        "Pending",
        dueDate,
      ]
    );

    return res.json({
      success: true,
      message: "Invoice created successfully",
      invoice: result.rows[0],
    });
  } catch (error) {
    console.error("CREATE INVOICE ERROR:", error);
    return res.status(500).json({
      success: false,
      message: "Failed to create invoice",
    });
  }
});

